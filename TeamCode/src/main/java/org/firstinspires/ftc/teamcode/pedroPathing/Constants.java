package org.firstinspires.ftc.teamcode.pedroPathing;

import com.pedropathing.algorithm.Foresight;
import com.pedropathing.algorithm.ForesightConfig;
import com.pedropathing.follower.Follower;
import com.pedropathing.revhub.drivetrains.Mecanum;
import com.pedropathing.revhub.drivetrains.MecanumConfig;
import com.pedropathing.revhub.localizers.PinpointConfig;
import com.pedropathing.revhub.localizers.PinpointLocalizer;
import com.qualcomm.robotcore.hardware.HardwareMap;

import org.firstinspires.ftc.robotcore.external.navigation.DistanceUnit;
import org.firstinspires.ftc.teamcode.config.HardwareNames;
import org.firstinspires.ftc.teamcode.config.RobotConstants;

/** Shared Pedro 3 configuration for driving and AutoTune. */
public final class Constants {
    private Constants() { }

    public static MecanumConfig drivetrainConfig = new MecanumConfig(c -> {
        c.frontLeftName.set(HardwareNames.LEFT_FRONT_DRIVE);
        c.backLeftName.set(HardwareNames.LEFT_BACK_DRIVE);
        c.frontRightName.set(HardwareNames.RIGHT_FRONT_DRIVE);
        c.backRightName.set(HardwareNames.RIGHT_BACK_DRIVE);
        c.frontLeftDirection.set(RobotConstants.LEFT_DRIVE_DIRECTION);
        c.backLeftDirection.set(RobotConstants.LEFT_DRIVE_DIRECTION);
        c.frontRightDirection.set(RobotConstants.RIGHT_DRIVE_DIRECTION);
        c.backRightDirection.set(RobotConstants.RIGHT_DRIVE_DIRECTION);
        c.manualBrakeMode.set(true);
    });

    public static PinpointConfig localizerConfig = new PinpointConfig(c -> {
        c.name.set(HardwareNames.PINPOINT);
        // Pinpoint's X pod measures forward travel; its offset is measured sideways.
        c.xPodOffset.set(RobotConstants.FORWARD_POD_Y_INCHES);
        c.yPodOffset.set(RobotConstants.STRAFE_POD_X_INCHES);
        c.xPodDirection.set(RobotConstants.FORWARD_ENCODER_DIRECTION);
        c.yPodDirection.set(RobotConstants.STRAFE_ENCODER_DIRECTION);
        c.podType.set(RobotConstants.ODOMETRY_PODS);
        c.offsetUnits.set(DistanceUnit.INCH);
        c.globalDistanceUnit.set(DistanceUnit.INCH);
    });

    // Replace null with the ForesightConfig generated by AutoTune before following paths.
    // The current TeleOps and timed TemplateAuto use manual driving and do not need it.
    public static ForesightConfig foresightConfig = null;

    public static Follower createManual(HardwareMap hardwareMap) {
        return new Follower(new PinpointLocalizer(hardwareMap, localizerConfig),
                new Mecanum(hardwareMap, drivetrainConfig), null);
    }

    /** For future autonomous paths/holding, after applying the Foresight tuning results. */
    public static Follower create(HardwareMap hardwareMap) {
        if (foresightConfig == null) {
            throw new IllegalStateException("Run Foresight AutoTune and fill Constants.foresightConfig first.");
        }
        return new Follower(new PinpointLocalizer(hardwareMap, localizerConfig),
                new Mecanum(hardwareMap, drivetrainConfig), new Foresight(foresightConfig));
    }
}
